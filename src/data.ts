const qcCheck = (
  id: ComparabilityCheck['id'],
  label: LocalizedText,
  passed: boolean,
  detail: LocalizedText,
  critical = false,
): ComparabilityCheck => ({ id, label, passed, detail, critical })

const makeSite = (
  status: ComparisonStatus,
  site: MeasurementSite,
  label: LocalizedText,
  baselineBmd: number,
  currentBmd: number,
  lscPercent: number,
  history: TrendPoint[],
) => calculateSiteChange({ site, label, baselineBmd, currentBmd, lscPercent, history }, status)

const makeLongitudinal = (input: Omit<LongitudinalAnalysis, 'intervalMonths' | 'assumed'>): LongitudinalAnalysis => ({
  ...input,
  intervalMonths: monthsBetween(input.baselineDate, input.currentDate),
  assumed: true,
})

