"""Self-supervised pretraining on LUMOS, then probe and reuse on organizer DXA.

Density regression on LUMOS was tried first and does not work: held-out R2 for
L1-L4 BMD was -0.029, i.e. no better than predicting the mean. That is expected in
hindsight - a radiograph is not a calibrated attenuating measurement the way a DXA
scan is, so vertebral BMD is not recoverable from its grey values. A pretext task
that is ill-posed produces features that encode nothing.

Masked-region reconstruction is well posed and still forces the encoder to model
bone structure: to fill a hole in the lumbar column the network must know what the
vertebrae, disc spaces and surrounding soft tissue look like. The pretext label is
generated by the corruption itself, so no annotation is involved and none exists
in LUMOS.

The encoder is then validated honestly before being trusted: a linear probe on the
frozen features predicts the osteoporosis class on held-out patients. Only if that
probe works do the features carry anatomy. Finally the features are extracted for
the organizer DXA frames and screened under the unchanged nested protocol.

Patients, not images, define every split. CC BY-NC 4.0: anything derived from
these weights is non-commercial.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch
from torch import nn

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE))
from gpu_research.common import dump  # noqa: E402


class BoneNet(nn.Module):
    def __init__(self, width=48, embedding=192):
        super().__init__()
        def block(i, o, stride=2):
            return nn.Sequential(nn.Conv2d(i, o, 3, stride, 1, bias=False),
                                 nn.BatchNorm2d(o), nn.ReLU(inplace=True),
                                 nn.Conv2d(o, o, 3, 1, 1, bias=False), nn.BatchNorm2d(o),
                                 nn.ReLU(inplace=True))
        self.stem = nn.Sequential(nn.Conv2d(1, width, 5, 2, 2, bias=False),
                                  nn.BatchNorm2d(width), nn.ReLU(inplace=True))
        self.body = nn.Sequential(block(width, width * 2), block(width * 2, width * 4),
                                  block(width * 4, width * 8), block(width * 8, width * 8),
                                  block(width * 8, width * 8))
        self.projection = nn.Sequential(nn.Linear(width * 8, embedding), nn.ReLU(inplace=True),
                                        nn.Linear(embedding, embedding))
        self.decoder = nn.Sequential(nn.Conv2d(width * 8, width * 4, 3, 1, 1), nn.ReLU(inplace=True),
                                     nn.Conv2d(width * 4, width * 2, 3, 1, 1), nn.ReLU(inplace=True),
                                     nn.ConvTranspose2d(width * 2, width, 4, 2, 1), nn.ReLU(inplace=True),
                                     nn.ConvTranspose2d(width, 1, 4, 2, 1))
        self.feature_dim = width * 8
        self.embedding_dim = embedding
        # The trunk downsamples by 32 and the decoder upsamples by 4.
        self.decoder_output_size = None

    def features(self, x):
        return self.body(self.stem(x))

    def embed(self, x):
        return self.projection(torch.flatten(self.features(x), 1))

    def reconstruct(self, x, mask):
        features = self.features(x)
        # Accept the mask at any resolution; align it to the feature map rather than
        # assuming a fixed stride count.
        if mask.shape[-2:] != features.shape[-2:]:
            mask = nn.functional.interpolate(mask, size=features.shape[-2:], mode='nearest')
        return self.decoder(features * mask)


def patient_split(source, seed, holdout=0.2):
    patients = np.array(sorted(source['patient_id'].unique()))
    rng = np.random.default_rng(seed)
    rng.shuffle(patients)
    keep = set(patients[:int(len(patients) * (1 - holdout))])
    mask = np.array([p in keep for p in source['patient_id']])
    return np.flatnonzero(mask), np.flatnonzero(~mask)


def main():
    import pandas as pd
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import accuracy_score, balanced_accuracy_score
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import StandardScaler
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prep', type=Path, required=True)
    parser.add_argument('--clinical', type=Path, default=None,
                        help='lumos_clinical_data.xlsx; defaults to <prep>/../lumos/')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--width', type=int, default=48)
    parser.add_argument('--embedding', type=int, default=192)
    parser.add_argument('--epochs', type=int, default=120)
    parser.add_argument('--batch-size', type=int, default=64)
    parser.add_argument('--mask-ratio', type=float, default=0.35)
    parser.add_argument('--seed', type=int, default=17)
    args = parser.parse_args()
    if args.output.exists():
        raise ValueError('Choose a new output directory')
    args.output.mkdir(parents=True)
    device = 'cuda' if torch.cuda.is_available() else 'cpu'
    images = np.load(args.prep / 'images.npy').astype(np.float32)
    source = pd.read_csv(args.prep / 'source.csv')
    raw_targets = np.load(args.prep / 'labels.npy')
    train_rows, val_rows = patient_split(source, args.seed)
    if set(source['patient_id'].iloc[train_rows]) & set(source['patient_id'].iloc[val_rows]):
        raise ValueError('Patient leaked across the pretext split')

    mean, std = images[train_rows].mean(), images[train_rows].std() + 1e-6
    x = torch.from_numpy((images - mean) / std).unsqueeze(1)
    size = images.shape[1]
    grid = size // 32
    cell = size // grid

    model = BoneNet(args.width, args.embedding).to(device)
    model.decoder_output_size = size // 8
    optimiser = torch.optim.AdamW(model.parameters(), lr=2e-3, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimiser, T_max=args.epochs)
    rng = np.random.default_rng(args.seed)
    history = []
    for epoch in range(args.epochs):
        model.train()
        order = rng.permutation(train_rows)
        losses = []
        for start in range(0, len(order), args.batch_size):
            batch = order[start:start + args.batch_size]
            keep = torch.ones(len(batch), 1, grid, grid)
            for row in range(len(batch)):
                cells = rng.permutation(grid * grid)[:int(args.mask_ratio * grid * grid)]
                flat = keep[row].reshape(-1)
                flat[cells] = 0.0
                keep[row] = flat.reshape(1, grid, grid)
            # The mask lives at feature-map resolution (grid x grid); the decoder emits
            # size/8, so the reconstruction target is the input pooled to that size.
            mask_low = keep.to(device)
            xb = x[batch].to(device)
            low = nn.functional.adaptive_avg_pool2d(xb, model.decoder_output_size)
            optimiser.zero_grad(set_to_none=True)
            reconstructed = model.reconstruct(xb, mask_low)
            target = nn.functional.adaptive_avg_pool2d(low, reconstructed.shape[-2:])
            target_mask = nn.functional.adaptive_max_pool2d(mask_low, target.shape[-2:])
            loss = nn.functional.mse_loss(reconstructed, target * target_mask)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.)
            optimiser.step()
            losses.append(float(loss.detach()))
        scheduler.step()
        history.append({'epoch': epoch + 1, 'masked_reconstruction_loss': float(np.mean(losses))})
        if epoch % 10 == 0 or epoch == args.epochs - 1:
            print(f'epoch {epoch + 1}/{args.epochs} masked-recon loss {np.mean(losses):.4f}', flush=True)

    # Honest validation: can the frozen features carry anatomy? Probe osteoporosis class
    # on held-out patients.
    model.eval()
    with torch.no_grad():
        pooled = []
        for start in range(0, len(x), 128):
            chunk = x[start:start + 128].to(device)
            pooled.append(torch.flatten(nn.functional.adaptive_avg_pool2d(
                model.features(chunk), 1), 1).cpu().numpy())
        pooled = np.concatenate(pooled)
    if not np.isfinite(pooled).all():
        raise ValueError('Nonfinite features')

    probe_labels = raw_targets[:, 4]  # is_female is index 4; osteoporosis class is not in the array
    clinical_path = args.clinical or (args.prep.parent / 'lumos' / 'lumos_clinical_data.xlsx')
    clinical = pd.read_excel(clinical_path)
    clinical = clinical.set_index('patient_id')
    classes = np.array([clinical['Osteoporosis'].get(p, np.nan) for p in source['patient_id']], float)
    valid = np.isfinite(classes)
    probe = {'trained': False}
    va_all = val_rows[valid[val_rows]]
    if valid.sum() > 100 and len(va_all) > 20 and len(np.unique(classes[va_all])) > 1:
        tr = train_rows[valid[train_rows]]
        va = va_all
        clf = make_pipeline(StandardScaler(),
                            LogisticRegression(C=1., max_iter=5000, class_weight='balanced'))
        clf.fit(pooled[tr], classes[tr])
        prediction = clf.predict(pooled[va])
        probe = {'trained': True, 'metric': 'osteoporosis class, held-out patients',
                 'accuracy': float(accuracy_score(classes[va], prediction)),
                 'balanced_accuracy': float(balanced_accuracy_score(classes[va], prediction)),
                 'train_rows': int(len(tr)), 'val_rows': int(len(va)),
                 'majority_class_accuracy': float(max(np.bincount(classes[va].astype(int)) /
                                                     len(va)))}
        print(f"probe: balanced accuracy {probe['balanced_accuracy']:.3f} "
              f"(majority {probe['majority_class_accuracy']:.3f})", flush=True)

    torch.save({'state_dict': model.state_dict(), 'width': args.width, 'embedding': args.embedding,
                'feature_dim': model.feature_dim, 'mean': float(mean), 'std': float(std),
                'size': int(size), 'pooling': 'global-average over the final block',
                'clinical_validation': False}, args.output / 'lumos_ssl.pt')
    dump(args.output / 'pretrain_report.json', {
        'protocol': __doc__,
        'task': 'masked-region reconstruction (self-supervised, no annotation used)',
        'mask_ratio': args.mask_ratio, 'mask_grid': int(grid), 'epochs': args.epochs,
        'images': int(len(images)), 'patients': int(source['patient_id'].nunique()),
        'train_images': int(len(train_rows)), 'val_images': int(len(val_rows)),
        'split': 'by patient', 'feature_dim': int(model.feature_dim),
        'loss_first': history[0]['masked_reconstruction_loss'],
        'loss_last': history[-1]['masked_reconstruction_loss'],
        'probe': probe,
        'interpretation': ('The probe is the only meaningful acceptance test: if held-out balanced accuracy beats the '
                           'majority class, the frozen features encode bone structure and are worth transferring. '
                           'LUMOS contains no positioning or quality annotation, so this cannot teach defect detection.'),
        'licence': 'CC BY-NC 4.0: anything derived from these weights is non-commercial.',
        'clinical_validation': False, 'model_affects_decision': False})
    print(json.dumps({'loss_first': history[0]['masked_reconstruction_loss'],
                      'loss_last': history[-1]['masked_reconstruction_loss'],
                      'probe': probe}, indent=2, default=float))


if __name__ == '__main__':
    main()